const { test, expect } = require('@playwright/test');
test('signup, persistence, logout, validation and login', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByText('Welcome back.')).toBeVisible();
  await page.screenshot({path:'docs/login.png',fullPage:true});
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await expect(page.getByText('Please enter your email.')).toBeVisible();
  await page.getByRole('button',{name:/Go to Signup/}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Alex Morgan');
  await page.getByLabel('Email address',{exact:true}).filter({visible:true}).fill('alex@example.com');
  await page.getByLabel('Password',{exact:true}).filter({visible:true}).fill('secret123');
  await page.getByRole('button',{name:'Show password',exact:true}).click();
  await expect(page.getByLabel('Password',{exact:true}).filter({visible:true})).toHaveJSProperty('type','text');
  await page.getByRole('button',{name:'Hide password',exact:true}).click();
  await page.screenshot({path:'docs/signup.png',fullPage:true});
  await page.getByRole('button',{name:'Signup',exact:true}).click();
  await expect(page.getByText('Hello, Alex.')).toBeVisible();
  await expect(page.getByText('alex@example.com',{exact:true})).toBeVisible();
  await page.screenshot({path:'docs/home.png',fullPage:true});
  await page.reload();
  await expect(page.getByText('Hello, Alex.')).toBeVisible();
  await page.getByRole('button',{name:'Logout',exact:true}).click();
  await expect(page.getByText('Welcome back.')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Welcome back.')).toBeVisible();
  await page.getByLabel('Email address',{exact:true}).filter({visible:true}).fill('alex@example.com');
  await page.getByLabel('Password',{exact:true}).filter({visible:true}).fill('wrong123');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await expect(page.getByText('Incorrect email or password. Please try again.')).toBeVisible();
  await page.getByRole('button',{name:/Go to Signup/}).click();
  await page.getByLabel('Full name',{exact:true}).fill('Another Alex');
  await page.getByLabel('Email address',{exact:true}).filter({visible:true}).fill('ALEX@example.com');
  await page.getByLabel('Password',{exact:true}).filter({visible:true}).fill('secret123');
  await page.getByRole('button',{name:'Signup',exact:true}).click();
  await expect(page.getByText('An account with this email already exists. Please log in.')).toBeVisible();
  await page.getByRole('button',{name:/Go to Login/}).click();
  await page.getByLabel('Email address',{exact:true}).filter({visible:true}).fill(' ALEX@example.com ');
  await page.getByLabel('Password',{exact:true}).filter({visible:true}).fill('secret123');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await expect(page.getByText('Hello, Alex.')).toBeVisible();
});
